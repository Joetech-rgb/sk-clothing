#!/usr/bin/env bash
# Writes infra/nginx/cloudflare/real-ip.conf from Cloudflare's published address lists, so nginx
# trusts the CF-Connecting-IP header only from Cloudflare. Run it on the server, then reload nginx:
#   bash infra/nginx/update-cloudflare-ips.sh && docker compose -f docker-compose.prod.yml exec nginx nginx -s reload
# The lists change rarely; run it again now and then (monthly is enough). Nothing is written if a
# download fails or looks wrong.
set -euo pipefail

OUT="${OUT:-infra/nginx/cloudflare/real-ip.conf}"
V4_URL="${V4_URL:-https://www.cloudflare.com/ips-v4}"
V6_URL="${V6_URL:-https://www.cloudflare.com/ips-v6}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

echo "# Generated by update-cloudflare-ips.sh. Do not edit by hand." > "$tmp"
count=0
for url in "$V4_URL" "$V6_URL"; do
  body="$(curl -fsS --max-time 20 "$url")"
  while IFS= read -r line; do
    line="${line%%[[:space:]]*}"
    [ -z "$line" ] && continue
    if ! [[ "$line" =~ ^[0-9A-Fa-f:.]+/[0-9]{1,3}$ ]]; then
      echo "Unexpected line from $url: $line" >&2
      exit 1
    fi
    echo "set_real_ip_from $line;" >> "$tmp"
    count=$(( count + 1 ))
  done <<< "$body"
done

if [ "$count" -lt 5 ]; then
  echo "Only $count ranges downloaded. Refusing to write $OUT." >&2
  exit 1
fi
echo "real_ip_header CF-Connecting-IP;" >> "$tmp"
mkdir -p "$(dirname "$OUT")"
mv "$tmp" "$OUT"
trap - EXIT
echo "Wrote $count ranges to $OUT"
